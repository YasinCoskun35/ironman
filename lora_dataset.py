#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
lora_dataset.py — turn our existing Cut-Ready outputs into a LoRA training set.

Scans a folder tree (e.g. the etsy/ folder with one subfolder per listing) for
the files mycode.py writes — found through the cnc_prep_report.json it leaves
next to them, or the "Generated by cnc_prep.py" stamp in its SVGs — keeps one
cut file per design, and writes:

    <out>/0001.png  0001.txt  ...   1024x1024, pure black on white, design centred
    <out>/captions.csv              file, caption, source  (edit captions here, then --apply-captions)
    <out>/dataset_sheet.jpg         every image numbered, to delete the weak ones before training

Each caption starts with the trigger word, then the subject. The subject comes
from the source file name: Firefly names its downloads after the prompt
("Firefly_gpt-image_A long Chinese dragon curving ..."), which is a ready caption.

USAGE
-----
    python lora_dataset.py -i ~/etsy -o lora_data
    python lora_dataset.py -i ~/etsy -o lora_data --trigger ifcsteel --size 768
    python lora_dataset.py -o lora_data --apply-captions      # after editing captions.csv
    python lora_dataset.py -o lora_data --train-config        # write train_ifcsteel.json for mflux-train
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional, Sequence

import numpy as np
from PIL import Image, ImageDraw, ImageFont

import mycode as cnc

STAMP = "Generated by cnc_prep.py"


def find_cut_files(root: Path) -> List[Path]:
    """
    One cut file per design. A design cut at several sizes leaves the same stem
    in several folders; training on five copies of one dragon teaches the
    dragon, not the style, so only the first is kept. PNG is preferred (no SVG
    rasteriser needed), SVG otherwise.
    """
    found: Dict[str, Path] = {}

    def add(p: Path) -> None:
        key = re.sub(r"[^a-z0-9]+", "", p.stem.lower())
        if p.suffix.lower() == ".png" and p.stem.endswith("_preview"):
            return
        cur = found.get(key)
        if cur is None or (cur.suffix.lower() == ".svg" and p.suffix.lower() == ".png"):
            found[key] = p

    for rep in root.rglob("cnc_prep_report.json"):
        try:
            data = json.loads(rep.read_text(encoding="utf-8"))
        except Exception:
            continue
        for d in data.get("designs", []):
            for o in d.get("outputs", []):
                p = Path(o)
                if not p.exists():
                    p = rep.parent / p.name          # report written on another machine/path
                if p.exists() and p.suffix.lower() in (".png", ".svg"):
                    add(p)
    for svg in root.rglob("*.svg"):
        try:
            head = svg.read_text(encoding="utf-8", errors="ignore")[:2000]
        except Exception:
            continue
        if STAMP in head:
            add(svg)
    return sorted(found.values(), key=lambda p: str(p).lower())


def caption_from_name(stem: str) -> str:
    """'Firefly_gpt-image_A long Chinese dragon curving ... 26471' -> 'a long chinese dragon curving ...'"""
    s = stem.replace("_", " ")
    s = re.sub(r"^\s*firefly\s*", "", s, flags=re.I)
    s = re.sub(r"^\s*gpt[- ]?image\s*", "", s, flags=re.I)
    s = re.sub(r"\s+\d{3,}$", "", s)
    s = re.sub(r"\b(20\d{8}|\d{10})\b", "", s)            # SKUs
    s = re.sub(r"\bchatgpt image\b.*", "", s, flags=re.I)
    s = re.sub(r"\b\d+(x\d+)?\s?(mm|cm)\b", "", s, flags=re.I)     # 700mm, 120x38cm
    s = re.sub(r"\b(x{0,3}-?small|medium|x{0,3}-?large|temiz|duzeltilmis|final|kesim|cut|preview)\b", "",
               s, flags=re.I)
    s = re.sub(r"\s+", " ", s).strip(" -_.,")
    return s.lower()


def to_square(path: Path, size: int) -> Image.Image:
    """The design as Cut-Ready binarises it, cropped to its ink and centred on a white square."""
    cfg = cnc.Config(width_mm=600.0)
    gray, w_mm, _ = cnc.load_source(path, cfg)
    cfg.mm_per_px = w_mm / gray.shape[1]
    mask = cnc.binarize(gray, cfg)
    im = Image.fromarray(np.where(mask > 0, 0, 255).astype(np.uint8))
    bbox = Image.fromarray(mask).getbbox()
    if bbox:
        im = im.crop(bbox)
    inner = int(size * 0.88)                                # keep a white margin like the training targets
    im.thumbnail((inner, inner), Image.LANCZOS)
    canvas = Image.new("L", (size, size), 255)
    canvas.paste(im, ((size - im.width) // 2, (size - im.height) // 2))
    return canvas.point(lambda v: 0 if v < 128 else 255)


def sheet(items: List[Path], dest: Path, cols: int = 8, cell: int = 220) -> None:
    rows = (len(items) + cols - 1) // cols
    img = Image.new("RGB", (cols * cell, rows * (cell + 30)), "white")
    d = ImageDraw.Draw(img)
    try:
        font = ImageFont.truetype("DejaVuSans.ttf", 18)
    except OSError:
        font = ImageFont.load_default()
    for k, p in enumerate(items):
        im = Image.open(p).convert("RGB")
        im.thumbnail((cell - 10, cell - 10))
        x, y = (k % cols) * cell, (k // cols) * (cell + 30)
        img.paste(im, (x + 5, y + 5))
        d.text((x + 8, y + cell), p.stem, fill=(40, 40, 40), font=font)
    img.save(dest, quality=85)


def build(root: Path, out: Path, trigger: str, size: int, log=print) -> int:
    files = find_cut_files(root)
    if not files:
        log(f"error: no Cut-Ready outputs found under {root}")
        return 2
    out.mkdir(parents=True, exist_ok=True)
    rows, made, seen = [], [], []
    k = 0
    for src in files:
        try:
            square = to_square(src, size)
        except Exception as exc:                              # one unreadable file must not stop the set
            log(f"  atlandı: {src} ({exc})")
            continue
        # The same design re-exported under another name (a kit's SKU_size copy,
        # a "_temiz" fix) slips past the name check; compare the pictures.
        h = np.asarray(square.resize((32, 32), Image.BILINEAR), np.uint8) < 128
        if any(np.mean(h != o) < 0.04 for o in seen):
            log(f"  tekrar, atlandı: {src.name}")
            continue
        seen.append(h)
        k += 1
        name = f"{k:04d}"
        square.save(out / f"{name}.png")
        subject = caption_from_name(src.stem) or caption_from_name(src.parent.name) or "metal wall art design"
        caption = f"{trigger} style, {subject}, black laser-cut steel cut file, one connected piece"
        (out / f"{name}.txt").write_text(caption, encoding="utf-8")
        rows.append([f"{name}.png", caption, str(src)])
        made.append(out / f"{name}.png")
    with (out / "captions.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["file", "caption", "source"])
        w.writerows(rows)
    sheet(made, out / "dataset_sheet.jpg")
    log(f"{len(made)} görsel -> {out}  (kontrol: {out / 'dataset_sheet.jpg'}, açıklamalar: {out / 'captions.csv'})")
    return 0


# Previews mflux-train draws while it learns: subjects that are NOT in the set,
# so they show whether the style carries over or the model only memorised.
PREVIEWS = ["a lighthouse on rocks with crashing waves",
            "a fox curled around a crescent moon with pine branches"]


def write_train_config(out: Path, trigger: str, epochs: int = 15, size: Optional[int] = None) -> Path:
    """
    A LoRA config for mflux-train on a 16 GB Mac. mflux no longer trains FLUX.1,
    so this targets Z-Image Turbo (Apache 2.0, not gated; batch_generate --lora
    then generates with it). Memory: 4-bit base, disk-cached encodings
    (low_ram) and gradient checkpointing; the resolution follows the dataset.
    """
    out = out.expanduser().resolve()
    images = sorted(out.glob("[0-9][0-9][0-9][0-9].png"))
    n = len(images)
    if size is None:
        size = min(Image.open(images[0]).width, 1024) if images else 768
    for k, subject in enumerate(PREVIEWS, 1):
        (out / f"preview_{k}.txt").write_text(
            f"{trigger} style, {subject}, black laser-cut steel cut file, one connected piece", encoding="utf-8")
    blocks = {"start": 0, "end": 30}
    modules = ["attention.to_q", "attention.to_k", "attention.to_v", "attention.to_out.0",
               "feed_forward.w1", "feed_forward.w2", "feed_forward.w3"]
    conf = {
        "model": "z-image-turbo",
        "data": str(out),
        "seed": 4,
        "steps": 9,
        "guidance": 0.0,
        "quantize": 4,
        "max_resolution": size,
        "low_ram": True,
        "gradient_checkpointing": True,
        "training_loop": {"num_epochs": epochs, "batch_size": 1, "timestep_low": 4, "timestep_high": 9},
        "optimizer": {"name": "AdamW", "learning_rate": 1e-4},
        "checkpoint": {"save_frequency": 100, "output_path": str(out.parent / "lora_train")},
        "monitoring": {"preview_width": size, "preview_height": size, "plot_frequency": 20,
                       "generate_image_frequency": 100},
        "lora_layers": {"targets": [{"module_path": f"layers.{{block}}.{m}", "blocks": blocks, "rank": 16}
                                    for m in modules]},
    }
    dest = out.parent / f"train_{trigger}.json"
    dest.write_text(json.dumps(conf, indent=2), encoding="utf-8")
    print(f"{dest}  ({n} görsel × {epochs} tur = {n * epochs} adım, her 100 adımda checkpoint ve önizleme)")
    return dest


def apply_captions(out: Path) -> int:
    """Write captions.csv edits back to the .txt files; rows whose image was deleted are skipped."""
    n = 0
    with (out / "captions.csv").open(newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            img = out / r["file"]
            if img.exists():
                img.with_suffix(".txt").write_text(r["caption"].strip(), encoding="utf-8")
                n += 1
    for txt in out.glob("*.txt"):                            # captions of deleted images
        if not txt.stem.startswith("preview") and not txt.with_suffix(".png").exists():
            txt.unlink()
    print(f"{n} açıklama güncellendi")
    return 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(prog="lora_dataset", description="Build a LoRA training set from Cut-Ready outputs.")
    ap.add_argument("-i", "--input", type=Path, help="folder to scan (e.g. ~/etsy)")
    ap.add_argument("-o", "--output", required=True, type=Path, help="dataset folder")
    ap.add_argument("--trigger", default="ifcsteel", help="trigger word that switches the style on")
    ap.add_argument("--size", type=int, default=1024, help="square image size (768 trains faster on 16 GB)")
    ap.add_argument("--apply-captions", action="store_true", help="copy edited captions.csv into the .txt files")
    ap.add_argument("--train-config", action="store_true", help="write the mflux-train config next to the dataset")
    ap.add_argument("--epochs", type=int, default=15, help="passes over the dataset for --train-config")
    a = ap.parse_args(argv)
    if a.apply_captions or a.train_config:
        if a.apply_captions:
            apply_captions(a.output)
        if a.train_config:
            write_train_config(a.output, a.trigger, a.epochs)
        return 0
    if not a.input:
        ap.error("-i/--input is required unless --apply-captions")
    return build(a.input.expanduser(), a.output, a.trigger, a.size)


if __name__ == "__main__":
    sys.exit(main())
