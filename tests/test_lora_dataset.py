"""
Tests for lora_dataset.py on a fake etsy/ tree: finding Cut-Ready outputs,
one file per design, captions from Firefly names, and the square B/W output.
"""

import json
import sys
from pathlib import Path

import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import lora_dataset as ld


def _design(path: Path):
    img = np.full((400, 800), 255, np.uint8)
    cv2.rectangle(img, (100, 100), (700, 300), 0, 25)
    cv2.imwrite(str(path), img)


def _tree(tmp_path: Path) -> Path:
    root = tmp_path / "etsy"
    a = root / "2026101902" / "out"
    a.mkdir(parents=True)
    stem = "Firefly_gpt-image_A long Chinese dragon curving across 26471"
    _design(a / f"{stem}.png")
    _design(a / f"{stem}_preview.png")
    (a / "cnc_prep_report.json").write_text(json.dumps(
        {"designs": [{"outputs": [str(a / f"{stem}.png"), str(a / f"{stem}_preview.png")]}]}), encoding="utf-8")
    b = root / "old" / "XL"                                   # same design cut again at another size
    b.mkdir(parents=True)
    _design(b / f"{stem}.png")
    (b / "cnc_prep_report.json").write_text(json.dumps({"designs": [{"outputs": [str(b / f"{stem}.png")]}]}),
                                            encoding="utf-8")
    c = root / "misc"
    c.mkdir()
    (c / "wave.svg").write_text('<svg xmlns="http://www.w3.org/2000/svg" width="100mm" height="50mm" '
                                'viewBox="0 0 100 50"><desc>Generated by cnc_prep.py.</desc>'
                                '<path d="M 10 10 H 90 V 40 H 10 Z"/></svg>', encoding="utf-8")
    _design(c / "mockup_room.png")                            # not a Cut-Ready output: ignored
    return root


def test_finds_one_file_per_design_and_skips_previews(tmp_path):
    files = ld.find_cut_files(_tree(tmp_path))
    names = sorted(p.name for p in files)
    assert names == ["Firefly_gpt-image_A long Chinese dragon curving across 26471.png", "wave.svg"]


def test_caption_from_firefly_name():
    assert ld.caption_from_name("Firefly_gpt-image_A long Chinese dragon curving across 26471") == \
        "a long chinese dragon curving across"
    assert ld.caption_from_name("2026101902") == ""


def test_build_writes_square_bw_pairs(tmp_path):
    root = _tree(tmp_path)
    out = tmp_path / "data"
    ld.build(root, out, "ifcsteel", 256, log=lambda *_: None)
    pngs = sorted(out.glob("*.png"))
    assert len(pngs) == 2
    im = cv2.imread(str(pngs[0]), cv2.IMREAD_GRAYSCALE)
    assert im.shape == (256, 256) and set(np.unique(im).tolist()) <= {0, 255}
    cap = (out / "0001.txt").read_text(encoding="utf-8")
    assert cap.startswith("ifcsteel style, a long chinese dragon")
    assert (out / "dataset_sheet.jpg").exists() and (out / "captions.csv").exists()


def test_apply_captions_drops_deleted_images(tmp_path):
    out = tmp_path / "data"
    ld.build(_tree(tmp_path), out, "ifcsteel", 128, log=lambda *_: None)
    (out / "0002.png").unlink()
    text = (out / "captions.csv").read_text(encoding="utf-8").replace("a long chinese dragon", "a red dragon")
    (out / "captions.csv").write_text(text, encoding="utf-8")
    ld.apply_captions(out)
    assert "a red dragon" in (out / "0001.txt").read_text(encoding="utf-8")
    assert not (out / "0002.txt").exists()
